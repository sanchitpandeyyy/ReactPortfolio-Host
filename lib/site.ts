function isLocal(url: string): boolean {
  return /^https?:\/\/(localhost|127\.0\.0\.1|0\.0\.0\.0|\[::1\])(:\d+)?/i.test(url);
}

/**
 * Absolute origin, no trailing slash, https enforced on public hosts.
 *
 * A localhost value in production is treated as misconfiguration: emitting
 * `http://localhost:3000` canonicals to Googlebot is far worse than ignoring
 * the variable.
 */
export function siteUrl(): string {
  const configured = process.env.SITE_URL?.trim();
  if (!configured) {
    return process.env.NODE_ENV === "production"
      ? PRODUCTION_ORIGIN
      : "http://localhost:3000";
  }

  let url = configured.replace(/\/+$/, "");
  if (!isLocal(url)) url = url.replace(/^http:\/\//i, "https://");

  if (process.env.NODE_ENV === "production" && isLocal(url)) {
    console.warn(
      `[seo] SITE_URL is "${configured}" in production; falling back to ${PRODUCTION_ORIGIN}.`,
    );
    return PRODUCTION_ORIGIN;
  }
  return url;
}

/** Join a path onto the site origin. Always absolute, never double-slashed. */
export function absoluteUrl(path = "/"): string {
  if (/^https?:\/\//i.test(path)) return path;
  return `${siteUrl()}${path.startsWith("/") ? path : `/${path}`}`;
}

